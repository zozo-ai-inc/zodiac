import { expect, test, type Page } from "@playwright/test";

import { seedLocalSettings, stubExternalTraffic } from "../helpers/app";

async function openApp(page: Page, openRouterResponses: Array<{ text: string }> = []): Promise<void> {
	await stubExternalTraffic(page, openRouterResponses);
	await seedLocalSettings(page);
	await page.addInitScript(() => {
		// Only seed thinking on the first load, so a reload keeps what the test changed.
		if (sessionStorage.getItem("reasoning-effort-seeded")) return;
		sessionStorage.setItem("reasoning-effort-seeded", "true");
		localStorage.setItem("enableThinking", "true");
	});
	await page.goto("/");
	await expect(page.locator("#btn-chat-add")).toBeVisible();
}

async function openChatSettings(page: Page): Promise<void> {
	await page.locator("#btn-open-settings").click();
	await page.locator('[data-settings-target="chat"]').click();
	await expect(page.locator("#model-picker-trigger")).toBeVisible();
}

async function pickModel(page: Page, family: string, modelId: string): Promise<void> {
	await page.locator("#model-picker-trigger").click();
	await page.locator("#model-picker-family-list .model-picker-family", { hasText: family }).click();
	await page.locator(`#model-picker-model-list [data-model-id="${modelId}"]`).click();
	await expect(page.locator("#selectedModel")).toHaveValue(modelId);
}

async function effortOptions(page: Page): Promise<string[]> {
	return await page
		.locator("#reasoningEffort option")
		.evaluateAll((options) => options.map((option) => (option as HTMLOptionElement).value));
}

test("offers only the selected model's effort levels and keeps the chosen effort across model switches and reload", async ({
	page
}) => {
	await openApp(page);
	await openChatSettings(page);
	const effortSelect = page.locator("#reasoningEffort");

	await expect(page.locator("#selectedModel")).toHaveValue("openai/gpt-5.4");
	await expect(effortSelect, "the effort picker does not default to high").toHaveValue("high");
	expect(await effortOptions(page)).toEqual(["low", "medium", "high", "xhigh"]);

	await pickModel(page, "Claude", "anthropic/claude-opus-4.8");
	expect(await effortOptions(page)).toEqual(["low", "medium", "high", "xhigh", "max"]);
	await effortSelect.selectOption("max");

	// GPT-5.4 has no Max, so it shows the nearest level without forgetting the choice
	await pickModel(page, "GPT", "openai/gpt-5.4");
	await expect(effortSelect, "Max is not shown as GPT-5.4's nearest level").toHaveValue("xhigh");

	await page.reload();
	await expect(page.locator("#btn-chat-add")).toBeVisible();
	await openChatSettings(page);
	await pickModel(page, "Claude", "anthropic/claude-opus-4.8");
	await expect(effortSelect, "the chosen Max effort was lost after switching models and reloading").toHaveValue(
		"max"
	);
	expect(await page.evaluate(() => localStorage.getItem("reasoningEffort"))).toBe("max");
});

test("hides the effort picker for models that only turn thinking on or off", async ({ page }) => {
	await openApp(page);
	await openChatSettings(page);

	await expect(page.locator("#reasoning-effort-setting")).toBeVisible();
	await pickModel(page, "GLM", "z-ai/glm-5");
	await expect(page.locator("#reasoning-effort-setting"), "GLM 5 offers effort levels it does not take").toBeHidden();
});

test("sends the chosen effort with an own-key OpenRouter chat request", async ({ page }) => {
	const chatRequestEfforts: unknown[] = [];
	page.on("request", (request) => {
		if (!request.url().startsWith("https://openrouter.ai/api/v1/chat/completions")) return;
		const body = request.postDataJSON() as { model?: string; reasoning?: unknown };
		// the new chat's title is generated by a separate request with its own model
		if (body.model === "openai/gpt-5.4") chatRequestEfforts.push(body.reasoning);
	});

	await openApp(page, [{ text: "Effort Chat" }, { text: "Thought hard about it." }]);
	await openChatSettings(page);
	await page.locator("#reasoningEffort").selectOption("low");
	await page.keyboard.press("Escape");

	await page.locator("#messageInput").fill("How hard will you think?");
	await page.locator("#btn-send").click();
	await expect(page.locator(".message").last()).toContainText("Thought hard about it.");

	expect(chatRequestEfforts, "the chat request did not carry the chosen effort").toEqual([
		{ effort: "low", exclude: false }
	]);
});
